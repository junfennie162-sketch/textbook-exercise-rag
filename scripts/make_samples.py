def make_textbook(path: Path) -> None:
    doc = Document()
    doc.add_heading("高中数学基础章节（样例教材，共十章）", level=0)
    for chapter, paragraphs in TEXTBOOK:
        doc.add_heading(chapter, level=1)
        for para in paragraphs:
            doc.add_paragraph(para)
    doc.save(str(path))


def make_exercise(path: Path) -> None:
    doc = Document()
    doc.add_heading("高中数学习题册（样例，共60题）", level=0)
    doc.add_paragraph(
        "说明：第1~10题对应教材第一至五章，第16~60题对应第六至十章；"
        "第11、13、14、15题属于化学、物理、英语、历史等其他学科，超出本教材范围，"
        "用于验证边界处理（应明确提示无教材依据，不得编造步骤）。"
    )
    for item in EXERCISES:
        doc.add_paragraph(item)
    doc.save(str(path))


def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    textbook_path = OUT_DIR / "样例教材_高中数学基础章节.docx"
    exercise_path = OUT_DIR / "样例习题册_高中数学60题.docx"
    make_textbook(textbook_path)
    make_exercise(exercise_path)
    print(f"OK textbook -> {textbook_path}")
    print(f"OK exercise -> {exercise_path}")

    for name in LEGACY_SAMPLE_FILES:
        legacy = OUT_DIR / name
        if legacy.exists():
            legacy.unlink()
            print(f"OK 清理历史样例 -> {legacy.name}")


if __name__ == "__main__":
    main()
